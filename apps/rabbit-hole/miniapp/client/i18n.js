export const MESSAGES = { zh, en };
let current = 'en';

/** Maps a language tag (the Host's en or zh-Hans, or navigator.language) to a message table. */
export const pickLang = (tag) => (/^zh(?:$|[-_])/i.test(String(tag ?? '')) ? 'zh' : 'en');
export function setLang(lang) { current = lang in MESSAGES ? lang : 'en'; }
export const getLang = () => current;
export function t(key, ...args) {
  const v = MESSAGES[current][key] ?? MESSAGES.en[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}
